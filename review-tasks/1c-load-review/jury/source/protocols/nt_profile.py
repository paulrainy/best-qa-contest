def half_up(x: float) -> int:
    return math.floor(x + 0.5)


def threads(code: str, percent: float) -> int:
    op = next(o for o in OPS if o[0] == code)
    return half_up(op[2] * percent / 100)


def target(code: str, percent: float) -> float:
    """Заданная интенсивность ступени, оп/ч: потоки × 3600 / пейсинг, для открытой модели — доля от 7 200."""
    op = next(o for o in OPS if o[0] == code)
    if op[3] is None:
        return op[4] * percent / 100
    return threads(code, percent) * 3600 / op[3]


def num(value, digits=0) -> str:
    """Число по-русски: пробел между разрядами, запятая в дробной части."""
    text = f'{value:,.{digits}f}'.replace(',', ' ').replace('.', ',')
    return text


def table(head, rows) -> str:
    lines = ['| ' + ' | '.join(head) + ' |', '| ' + ' | '.join('---' for _ in head) + ' |']
    lines += ['| ' + ' | '.join(str(c) for c in row) + ' |' for row in rows]
    return '\n'.join(lines)


